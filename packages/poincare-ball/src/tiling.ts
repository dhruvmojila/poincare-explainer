import type { Vec } from './math.js';
import { PoincareBall } from './ball.js';
import { geodesicArc, type Vec2 } from './arc.js';

/** One tile of a regular {p,q} tiling. */
export interface Tile {
  /** Centre of the tile in the Poincaré disk. */
  center: Vec2;
  /** The p vertices in cyclic order. */
  vertices: Vec2[];
  /** Number of reflections from the central tile (0 for the tile at the origin). */
  depth: number;
}

export interface TilingOptions {
  /** Curvature magnitude of the ball (or pass a `PoincareBall`). Default 1. */
  c?: number;
  ball?: PoincareBall;
  /** Rotation (radians) of the central tile's first vertex. Default 0. */
  angle?: number;
  /** Tiles whose centre has Euclidean norm above this fraction of the radius are not expanded. Default 0.995. */
  maxNorm?: number;
}

/**
 * Circumradius (centre-to-vertex hyperbolic distance) of the regular p-gon with interior
 * angle 2π/q, i.e. the face of the {p,q} tiling. In the right triangle centre–vertex–edge
 * midpoint the angles are π/p and π/q, so the hypotenuse r satisfies
 * cosh r = cot(π/p) · cot(π/q). Requires (p − 2)(q − 2) > 4 (hyperbolic case).
 */
export function tilingCircumradius(p: number, q: number): number {
  checkPQ(p, q);
  return Math.acosh(1 / (Math.tan(Math.PI / p) * Math.tan(Math.PI / q)));
}

/** Edge length of the {p,q} tiling: cosh(s/2) = cos(π/p) / sin(π/q). */
export function tilingEdgeLength(p: number, q: number): number {
  checkPQ(p, q);
  return 2 * Math.acosh(Math.cos(Math.PI / p) / Math.sin(Math.PI / q));
}

function checkPQ(p: number, q: number): void {
  if (!Number.isInteger(p) || !Number.isInteger(q) || p < 3 || q < 3) {
    throw new RangeError(`p and q must be integers >= 3, got {${p},${q}}`);
  }
  if ((p - 2) * (q - 2) <= 4) {
    throw new RangeError(`{${p},${q}} is not a hyperbolic tiling: need (p-2)(q-2) > 4`);
  }
}

/**
 * Reflect `z` across the geodesic through `a` and `b` (2-D).
 *
 * The geodesic is either a diameter (reflection = Euclidean mirror in that line) or a
 * circle orthogonal to the boundary (reflection = inversion in that circle,
 * z ↦ c + R² (z − c) / ||z − c||²). Both are hyperbolic isometries of the disk.
 */
export function reflectAcrossGeodesic(z: Vec, a: Vec, b: Vec, ball: PoincareBall = new PoincareBall(1)): Vec2 {
  if (z.length !== 2) throw new RangeError('reflectAcrossGeodesic is defined for 2-D points');
  const g = geodesicArc(a, b, ball);
  if (g.kind === 'segment') {
    let ux = g.to[0] - g.from[0];
    let uy = g.to[1] - g.from[1];
    const n = Math.hypot(ux, uy);
    if (n < 1e-15) throw new RangeError('a and b must be distinct');
    ux /= n;
    uy /= n;
    const d = z[0] * ux + z[1] * uy;
    return [2 * d * ux - z[0], 2 * d * uy - z[1]];
  }
  const dx = z[0] - g.center[0];
  const dy = z[1] - g.center[1];
  const k = (g.radius * g.radius) / (dx * dx + dy * dy);
  return [g.center[0] + k * dx, g.center[1] + k * dy];
}

/**
 * Regular {p,q} tiling of the hyperbolic plane by reflection: p-gons, q meeting at each
 * vertex, generated by reflecting the central tile across its edges and repeating up to
 * `depth` times. Reflections across geodesics are isometries, so every tile is congruent
 * to the central one; tiles are de-duplicated by their centre.
 *
 * {7,3} (the "heptagonal tiling") is the one drawn behind this explainer's title.
 */
export function regularTiling(p: number, q: number, depth: number, options: TilingOptions = {}): Tile[] {
  checkPQ(p, q);
  if (!Number.isInteger(depth) || depth < 0) throw new RangeError('depth must be a non-negative integer');
  const ball = options.ball ?? new PoincareBall(options.c ?? 1);
  const angle = options.angle ?? 0;
  const maxNorm = (options.maxNorm ?? 0.995) * ball.radius;

  const r = tilingCircumradius(p, q);
  const verts: Vec2[] = [];
  for (let k = 0; k < p; k++) {
    const th = angle + (2 * Math.PI * k) / p;
    const v = ball.pointAt([Math.cos(th), Math.sin(th)], r);
    verts.push([v[0], v[1]]);
  }
  const first: Tile = { center: [0, 0], vertices: verts, depth: 0 };
  const tiles: Tile[] = [first];
  const seen = new Set<string>([keyOf(first.center)]);

  let frontier = [first];
  for (let d = 1; d <= depth && frontier.length; d++) {
    const next: Tile[] = [];
    for (const tile of frontier) {
      if (Math.hypot(tile.center[0], tile.center[1]) > maxNorm) continue;
      const n = tile.vertices.length;
      for (let i = 0; i < n; i++) {
        const a = tile.vertices[i];
        const b = tile.vertices[(i + 1) % n];
        const center = reflectAcrossGeodesic(tile.center, a, b, ball);
        const key = keyOf(center);
        if (seen.has(key)) continue;
        seen.add(key);
        const vertices = tile.vertices.map((v) => reflectAcrossGeodesic(v, a, b, ball));
        const t: Tile = { center, vertices, depth: d };
        tiles.push(t);
        next.push(t);
      }
    }
    frontier = next;
  }
  return tiles;
}

function keyOf(p: Vec2): string {
  return `${Math.round(p[0] * 1e7)},${Math.round(p[1] * 1e7)}`;
}
